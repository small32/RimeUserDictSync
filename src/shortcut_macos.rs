//! macOS 快捷方式「同步词库」。
//!
//! Windows 用 `.lnk` 指向 `RimeUserDictSync.exe --sync-now`；macOS 没有 `.lnk`，
//! 这里用 `osacompile` 生成一个 AppleScript applet（`.app`），双击后执行
//! `RimeUserDictSync --sync-now --notify --app-dir <配置目录>`。
//!
//! 与 Windows 版保持同一语义：**完整一轮「同步词库」**——拉取远端 → 并集合并
//! → 写回本地 → 上传 → RIME `/sync` → `/reload`，而不是只跑 RIME 自带的两条命令。
//! 这样两端双击后的行为一致，也不会漏掉 Others/ 的合并与上传。
//!
//! 用 applet 而不是 `.command`：`.command` 双击会拉出一个 Terminal 窗口，
//! 而 applet 静默运行，更适合做成 Dock / 桌面图标。

use anyhow::{Context as _, Result, bail};
use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

pub const SHORTCUT_NAME: &str = "同步词库.app";
pub const SHORTCUT_TITLE: &str = "同步词库";

/// 标记文件：证明这个 `.app` 是本工具生成的。
///
/// 删除/覆盖前必须校验它，避免把用户自己放在同目录、恰好同名的应用删掉。
const MARKER_FILE: &str = "rime-sync-shortcut.marker";

/// 快捷方式位置：与 Windows 版一致，放在程序所在目录，由用户自行拖到 Dock 或桌面。
pub fn path(app_dir: &Path) -> PathBuf {
    app_dir.join(SHORTCUT_NAME)
}

pub fn exists(app_dir: &Path) -> bool {
    path(app_dir).is_dir()
}

pub fn describe(app_dir: &Path) -> String {
    let target = path(app_dir);
    if target.is_dir() {
        format!("快捷方式「{SHORTCUT_TITLE}」：{}", target.display())
    } else {
        format!(
            "快捷方式「{SHORTCUT_TITLE}」：未创建（会建在 {}）",
            app_dir.display()
        )
    }
}

pub fn install(app_dir: &Path) -> Result<String> {
    let exe = std::env::current_exe().context("无法确定程序路径")?;
    if !exe.is_file() {
        bail!("程序路径不存在：{}", exe.display());
    }
    let target = path(app_dir);
    if target.exists() && !is_ours(&target) {
        bail!(
            "{} 已存在且不是本工具创建的应用，请先手动移走再重试",
            target.display()
        );
    }

    // 关键：**不能**直接在目标目录里 osacompile。
    // 目标目录可能是 iCloud/FileProvider 或受管目录（本工具的配置目录默认就在
    // ~/Documents 下），在那里给 applet 签名会报
    // `replacing existing signature / Operation not permitted`（-4960）。
    // 先在临时目录完整构建、签名，最后整体 rename 过去——rename 只动目录项，
    // 不触碰包内可执行文件，不受这条限制。
    let staging = std::env::temp_dir().join(format!("rime-sync-shortcut-{}", std::process::id()));
    if staging.exists() {
        let _ = fs::remove_dir_all(&staging);
    }
    fs::create_dir_all(&staging).context("创建临时构建目录失败")?;
    let staged_app = staging.join(SHORTCUT_NAME);
    let script_path = staging.join("shortcut.applescript");
    fs::write(&script_path, apple_script(&exe, app_dir)).context("写入 AppleScript 失败")?;

    let output = Command::new("/usr/bin/osacompile")
        .arg("-o")
        .arg(&staged_app)
        .arg(&script_path)
        .output()
        .context("调用 osacompile 失败（macOS 自带组件，缺失说明系统异常）")?;
    if !output.status.success() {
        let _ = fs::remove_dir_all(&staging);
        bail!(
            "生成 AppleScript 应用失败：{}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    let _ = fs::remove_file(&script_path);

    let resources = staged_app.join("Contents/Resources");
    fs::create_dir_all(&resources)?;
    fs::write(
        resources.join(MARKER_FILE),
        b"generated by RimeUserDictSync\n",
    )?;
    // 用主程序自己的图标，Finder 里一眼能认出来。
    // applet 默认带一份 Assets.car，资产目录的优先级高于 applet.icns，
    // 所以换图标后要把它删掉，免得 Finder 仍显示通用脚本图标。
    let custom_icon = app_icon(&exe);
    if let Some(icon) = &custom_icon {
        let _ = fs::copy(icon, resources.join("applet.icns"));
        let _ = fs::remove_file(resources.join("Assets.car"));
    }

    let plist = staged_app.join("Contents/Info.plist");
    set_plist(&plist, "CFBundleDisplayName", SHORTCUT_TITLE);
    set_plist(&plist, "CFBundleName", SHORTCUT_TITLE);
    set_plist(
        &plist,
        "CFBundleIdentifier",
        "com.small32.rime-user-dict-sync.shortcut",
    );
    if custom_icon.is_some() {
        // 图标走 CFBundleIconFile=applet，指向已删资产目录的 CFBundleIconName 必须去掉。
        let _ = Command::new("/usr/libexec/PlistBuddy")
            .args(["-c", "Delete :CFBundleIconName"])
            .arg(&plist)
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status();
    }
    // 不占 Dock：双击时只跑任务、弹结果，不需要一个"正在运行的应用"。
    let _ = Command::new("/usr/libexec/PlistBuddy")
        .args(["-c", "Add :LSUIElement bool true"])
        .arg(&plist)
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();

    // 改过 Info.plist 与图标后原签名失效，必须重新 ad-hoc 签名，否则 Gatekeeper 会拦。
    let signed = Command::new("/usr/bin/codesign")
        .args(["--force", "--deep", "--sign", "-"])
        .arg(&staged_app)
        .output()
        .context("调用 codesign 失败")?;
    if !signed.status.success() {
        let _ = fs::remove_dir_all(&staging);
        bail!(
            "生成快捷方式失败：重新签名未通过：{}",
            String::from_utf8_lossy(&signed.stderr).trim()
        );
    }

    // 发布：旧包先挪进 staging（rename 不删包内文件），再把新包 rename 到位。
    // 直接 remove_dir_all 在 FileProvider 目录里也可能被拦，所以不这么做。
    let retired = staging.join("retired.app");
    if target.exists() {
        fs::rename(&target, &retired)
            .with_context(|| format!("移走旧快捷方式 {} 失败", target.display()))?;
    }
    fs::rename(&staged_app, &target)
        .with_context(|| format!("把快捷方式移动到 {} 失败", target.display()))?;
    let _ = fs::remove_dir_all(&retired);
    let _ = fs::remove_dir_all(&staging);

    Ok(format!(
        "已创建快捷方式：{}\n双击它会执行：拉取远端 → 并集合并 → 写回本地 → 上传 → RIME /sync → /reload。\n需要的话把它拖到 Dock 或桌面；主程序位置变化后请重新创建。",
        target.display()
    ))
}

pub fn uninstall(app_dir: &Path) -> Result<String> {
    let target = path(app_dir);
    if !target.is_dir() {
        return Ok(format!("没有找到「{SHORTCUT_TITLE}」快捷方式，无需删除。"));
    }
    if !is_ours(&target) {
        bail!(
            "{} 不是本工具创建的，拒绝删除；请确认后手动处理",
            target.display()
        );
    }
    // 同样先 rename 出受管目录，再在临时目录里删——直接删包内可执行文件可能被拦。
    let staging =
        std::env::temp_dir().join(format!("rime-sync-shortcut-rm-{}", std::process::id()));
    if staging.exists() {
        let _ = fs::remove_dir_all(&staging);
    }
    fs::rename(&target, &staging)
        .with_context(|| format!("删除 {} 失败（无法移出目标目录）", target.display()))?;
    fs::remove_dir_all(&staging).with_context(|| format!("清理 {} 失败", staging.display()))?;
    Ok(format!("已删除快捷方式「{SHORTCUT_TITLE}」。"))
}

fn is_ours(bundle: &Path) -> bool {
    bundle
        .join("Contents/Resources")
        .join(MARKER_FILE)
        .is_file()
}

/// 主程序的图标：`<App>.app/Contents/Resources/AppIcon.icns`。
fn app_icon(exe: &Path) -> Option<PathBuf> {
    let contents = exe.parent()?.parent()?;
    let icon = contents.join("Resources/AppIcon.icns");
    icon.is_file().then_some(icon)
}

fn set_plist(plist: &Path, key: &str, value: &str) {
    // Set 在键不存在时会失败，追加 Add 兜底；两者都失败也不影响主流程。
    for command in [
        format!("Set :{key} {value}"),
        format!("Add :{key} string {value}"),
    ] {
        let _ = Command::new("/usr/libexec/PlistBuddy")
            .arg("-c")
            .arg(command)
            .arg(plist)
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status();
    }
}

/// 生成 applet 的 AppleScript 源码。
///
/// - 用 `quoted form of` 处理路径里的空格与特殊字符；
/// - 先检查可执行文件是否存在，避免拖走主程序后双击毫无反应；
/// - 末尾 `; exit 0` 抑制 `do shell script` 的通用报错弹窗——成功/失败提示由
///   程序自己的 `--notify` 负责，避免失败时连弹两个对话框。
fn apple_script(exe: &Path, app_dir: &Path) -> String {
    let exe = applescript_literal(&exe.to_string_lossy());
    let app_dir = applescript_literal(&app_dir.to_string_lossy());
    format!(
        r#"on run
	set exePath to "{exe}"
	set appDir to "{app_dir}"
	if not (do shell script "test -x " & quoted form of exePath & " && echo yes || echo no") is "yes" then
		display dialog "找不到主程序：" & exePath & return & "请重新安装或重新创建快捷方式。" buttons {{"好"}} default button 1 with title "同步词库" with icon stop
		return
	end if
	do shell script quoted form of exePath & " --sync-now --notify --app-dir " & quoted form of appDir & " ; exit 0"
end run
"#
    )
}

fn applescript_literal(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shortcut_lives_next_to_the_executable() {
        let dir = Path::new("/Users/me/RimeUserDictSync");
        assert_eq!(path(dir), dir.join(SHORTCUT_NAME));
        assert!(SHORTCUT_NAME.ends_with(".app"));
        assert!(SHORTCUT_NAME.starts_with(SHORTCUT_TITLE));
    }

    #[test]
    fn script_quotes_paths_and_checks_the_binary() {
        let script = apple_script(
            Path::new("/Applications/RIME 工具/RimeUserDictSync"),
            Path::new("/Users/me/Rime Config"),
        );
        assert!(script.contains("quoted form of exePath"));
        assert!(script.contains("--sync-now --notify --app-dir"));
        assert!(script.contains("test -x"));
        assert!(script.contains(r#""/Applications/RIME 工具/RimeUserDictSync""#));
        assert!(script.contains(r#""/Users/me/Rime Config""#));
    }

    #[test]
    fn applescript_literals_escape_quotes_and_backslashes() {
        assert_eq!(applescript_literal(r#"a"b"#), r#"a\"b"#);
        assert_eq!(applescript_literal(r"a\b"), r"a\\b");
    }
}
